import {chromium} from 'playwright'
import assert from 'node:assert/strict'
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium-browser',headless:true,args:['--no-sandbox']})
try {
 for(const viewport of [{width:390,height:844},{width:1280,height:1000},{width:844,height:390}]){
  const context=await browser.newContext({viewport,isMobile:viewport.width===390,hasTouch:viewport.width===390})
  const page=await context.newPage()
  await page.goto(process.env.PREVIEW_URL||'http://127.0.0.1:3194')
  await page.getByRole('button',{name:'Day Notes',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'Day Notes',exact:true}),editor=dialog.getByRole('textbox',{name:'Period notes'})
  await editor.waitFor()
  assert.equal(await dialog.evaluate(e=>e===document.activeElement),true)
  assert.equal(await dialog.evaluate(e=>getComputedStyle(e).outlineStyle),'none')
  assert.equal(await dialog.getByRole('heading').getAttribute('tabindex'),null)
  await page.keyboard.press('Tab')
  assert.equal(await dialog.getByRole('button',{name:'Close planner details'}).evaluate(e=>e===document.activeElement),true)
  await page.keyboard.press('Tab');assert.equal(await dialog.getByRole('button',{name:'Bold',exact:true}).evaluate(e=>e===document.activeElement),true)
  const original=await dialog.boundingBox()
  assert.ok(Math.abs(original.height-viewport.height*.9)<2)
  for(const text of ['', 'A short note.', Array.from({length:100},(_,i)=>`Paragraph ${i+1}: a long note for reading and writing.`).join('\n')]){
   await editor.fill(text)
   await dialog.getByRole('status').filter({hasText:'Saved'}).waitFor()
   const box=await dialog.boundingBox(),writing=await editor.boundingBox(),status=await dialog.getByRole('status').boundingBox()
   assert.ok(Math.abs(box.height-original.height)<1 && Math.abs(box.y-original.y)<1)
   assert.ok(Math.abs(writing.x+writing.width-status.x-status.width)<1)
   assert.ok(writing.height>viewport.height*.4)
   assert.ok(status.y+status.height<=box.y+box.height)
   assert.equal(await dialog.getByRole('status').evaluate(e=>getComputedStyle(e).textAlign),'right')
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
   assert.equal(await dialog.evaluate(e=>e.scrollHeight>e.clientHeight),false)
  }
  assert.equal(await editor.evaluate(e=>e.scrollHeight>e.clientHeight),true)
  const toolbar=dialog.locator('.notes-toolbar'),toolbarBefore=await toolbar.boundingBox()
  await editor.press('Control+Home');await editor.press('Control+End')
  assert.ok(await editor.evaluate(e=>e.scrollTop>0))
  assert.deepEqual(await toolbar.boundingBox(),toolbarBefore)
  assert.equal(await toolbar.getByRole('button',{name:'Bold',exact:true}).isVisible(),true)
  await editor.press('Escape');await dialog.waitFor({state:'hidden'})
  assert.equal(await page.getByRole('button',{name:'Day Notes',exact:true}).evaluate(e=>e===document.activeElement),true)
  await page.getByRole('link',{name:'Week',exact:true}).click()
  await page.getByRole('button',{name:'Week Notes',exact:true}).click()
  const week=page.getByRole('dialog',{name:'Week Notes',exact:true})
  await week.getByRole('textbox',{name:'Period notes'}).waitFor()
  assert.equal(await week.evaluate(e=>e===document.activeElement),true)
  assert.ok(Math.abs((await week.boundingBox()).height-original.height)<1)
  await page.keyboard.press('Escape');await week.waitFor({state:'hidden'})
  await context.close()
 }
 console.log('PASS notes layout: neutral opening focus, Tab/Escape/restore, stable empty/short/long geometry, right-aligned status and editor scrolling at mobile, desktop and landscape sizes')
}finally{await browser.close()}
